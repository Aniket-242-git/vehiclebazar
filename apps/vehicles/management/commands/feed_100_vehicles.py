class Command(BaseCommand):
    help = "Seeds or updates exactly 100 complete, realistic vehicles with images, brands, categories and features."

    def add_arguments(self, parser):
        parser.add_argument(
            "--clean",
            action="store_true",
            help="Delete previously auto-seeded vehicles before feeding.",
        )

    def handle(self, *args, **options):
        self.stdout.write(self.style.NOTICE("Starting database feed for 100 vehicles..."))

        # 1. Brands
        brand_map: dict[str, Brand] = {}
        for b_name in BRANDS_DATA:
            b_slug = slugify(b_name)
            brand, _ = Brand.objects.get_or_create(
                slug=b_slug,
                defaults={"name": b_name, "is_active": True},
            )
            brand.name = b_name
            brand.is_active = True
            brand.save()
            brand_map[b_name] = brand
        self.stdout.write(self.style.SUCCESS(f"Processed {len(brand_map)} Brands."))

        # 2. Categories
        cat_map: dict[str, Category] = {}
        for c_info in CATEGORIES_DATA:
            cat_slug = c_info["slug"]
            cat, _ = Category.objects.get_or_create(
                slug=cat_slug,
                defaults={
                    "name": c_info["name"],
                    "description": c_info["description"],
                    "is_active": True,
                },
            )
            cat.name = c_info["name"]
            cat.description = c_info["description"]
            cat.is_active = True

            # Generate Category Tile Image if not already set
            if not cat.image:
                img_bytes = generate_category_card(c_info["name"], c_info["color"])
                cat.image.save(f"{cat_slug}.jpg", ContentFile(img_bytes), save=False)
            cat.save()
            cat_map[c_info["name"]] = cat
        self.stdout.write(self.style.SUCCESS(f"Processed {len(cat_map)} Categories with tile graphics."))

        # 3. Features
        feat_map: dict[str, Feature] = {}
        for f_name, f_slug, f_icon in FEATURES_DATA:
            feat, _ = Feature.objects.get_or_create(
                slug=f_slug,
                defaults={"name": f_name, "icon": f_icon, "is_active": True},
            )
            feat.name = f_name
            feat.icon = f_icon
            feat.is_active = True
            feat.save()
            feat_map[f_name] = feat
        self.stdout.write(self.style.SUCCESS(f"Processed {len(feat_map)} Features."))

        # 4. Optional clean: if requested, remove vehicles created earlier that match our titles
        if options.get("clean"):
            self.stdout.write("Cleaning previous catalogue entries...")
            Vehicle.objects.all().delete()

        # 5. Feed the 100 vehicles
        created_count = 0
        updated_count = 0

        self.stdout.write(f"Feeding {len(VEHICLES_CATALOGUE)} vehicles into the database...")

        for idx, item in enumerate(VEHICLES_CATALOGUE, 1):
            brand = brand_map.get(item["brand"])
            if not brand:
                brand, _ = Brand.objects.get_or_create(name=item["brand"], defaults={"slug": slugify(item["brand"])})
                brand_map[item["brand"]] = brand

            cat = cat_map.get(item["category"])
            if not cat:
                cat = Category.objects.filter(name__icontains=item["category"]).first() or list(cat_map.values())[0]

            v_slug = slugify(item["title"])[:210]

            vehicle, created = Vehicle.objects.get_or_create(
                slug=v_slug,
                defaults={
                    "title": item["title"],
                    "model_name": item["model_name"],
                    "brand": brand,
                    "category": cat,
                    "manufacturing_year": item["mfg_year"],
                    "registration_year": item["reg_year"],
                    "price": item["price"],
                    "offer_price": item["offer_price"],
                    "fuel_type": item["fuel"],
                    "transmission": item["trans"],
                    "km_driven": item["km"],
                    "engine_cc": item["engine_cc"],
                    "color": item["color"],
                    "ownership": item["ownership"],
                    "location": item["location"],
                    "description": item["desc"],
                    "status": item["status"],
                    "is_featured": item["is_featured"],
                    "is_active": True,
                },
            )

            if not created:
                # Update attributes
                vehicle.title = item["title"]
                vehicle.model_name = item["model_name"]
                vehicle.brand = brand
                vehicle.category = cat
                vehicle.manufacturing_year = item["mfg_year"]
                vehicle.registration_year = item["reg_year"]
                vehicle.price = item["price"]
                vehicle.offer_price = item["offer_price"]
                vehicle.fuel_type = item["fuel"]
                vehicle.transmission = item["trans"]
                vehicle.km_driven = item["km"]
                vehicle.engine_cc = item["engine_cc"]
                vehicle.color = item["color"]
                vehicle.ownership = item["ownership"]
                vehicle.location = item["location"]
                vehicle.description = item["desc"]
                vehicle.status = item["status"]
                vehicle.is_featured = item["is_featured"]
                vehicle.is_active = True
                vehicle.save()
                updated_count += 1
            else:
                created_count += 1

            # Attach ManyToMany features
            feature_objs = [feat_map[f] for f in item.get("features", []) if f in feat_map]
            if feature_objs:
                vehicle.features.set(feature_objs)

            # Generate and attach 2 high quality showcase images if not already attached
            existing_images_count = vehicle.images.count()
            if existing_images_count < 2:
                # Image 1: Main Studio Hero View (Primary)
                img1_bytes = generate_vehicle_image(
                    title=vehicle.title,
                    brand_name=brand.name,
                    category_name=cat.name,
                    year=vehicle.manufacturing_year,
                    fuel=vehicle.fuel_type,
                    transmission=vehicle.transmission,
                    km_driven=vehicle.km_driven,
                    price=vehicle.price,
                    offer_price=vehicle.offer_price,
                    location=vehicle.location,
                    view_type="EXTERIOR 3/4 SHOWCASE",
                    view_num=1,
                )
                img1_obj, _ = VehicleImage.objects.get_or_create(
                    vehicle=vehicle,
                    order=1,
                    defaults={"is_primary": True, "alt_text": f"{vehicle.title} Exterior View"},
                )
                img1_obj.is_primary = True
                img1_obj.alt_text = f"{vehicle.title} Exterior Showcase"
                img1_obj.image.save(f"{vehicle.slug}-1.jpg", ContentFile(img1_bytes), save=True)

                # Image 2: Cockpit & Tech View
                img2_bytes = generate_vehicle_image(
                    title=vehicle.title,
                    brand_name=brand.name,
                    category_name=cat.name,
                    year=vehicle.manufacturing_year,
                    fuel=vehicle.fuel_type,
                    transmission=vehicle.transmission,
                    km_driven=vehicle.km_driven,
                    price=vehicle.price,
                    offer_price=vehicle.offer_price,
                    location=vehicle.location,
                    view_type="COCKPIT & INTERIOR",
                    view_num=2,
                )
                img2_obj, _ = VehicleImage.objects.get_or_create(
                    vehicle=vehicle,
                    order=2,
                    defaults={"is_primary": False, "alt_text": f"{vehicle.title} Interior Cockpit"},
                )
                img2_obj.is_primary = False
                img2_obj.alt_text = f"{vehicle.title} Interior Cockpit"
                img2_obj.image.save(f"{vehicle.slug}-2.jpg", ContentFile(img2_bytes), save=True)

            if idx % 20 == 0 or idx == len(VEHICLES_CATALOGUE):
                self.stdout.write(f"  Processed {idx}/{len(VEHICLES_CATALOGUE)} vehicles...")

        # Safely cleanup old test dummy vehicles and re-link any contact request
        old_test_vehicles = Vehicle.objects.filter(brand__name="Tata Test")
