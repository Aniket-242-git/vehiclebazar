def _get_font(size: int, bold: bool = False):
    font_name = "arialbd.ttf" if bold else "arial.ttf"
    for path in [f"C:/Windows/Fonts/{font_name}", f"/usr/share/fonts/truetype/dejavu/DejaVuSans{'-Bold' if bold else ''}.ttf"]:
        try:
            return ImageFont.truetype(path, size)
        except Exception:
            continue
    return ImageFont.load_default()


def generate_category_card(name: str, color_rgb: tuple[int, int, int]) -> bytes:
    """Generate a clean, high quality 600x400 card for category tiles."""
    w, h = 600, 400
    img = Image.new("RGB", (w, h), (15, 23, 42))
    draw = ImageDraw.Draw(img)

    cr, cg, cb = color_rgb
    for y in range(h):
        factor = y / h
        r = int(cr * (1 - factor * 0.7) + 15 * factor)
        g = int(cg * (1 - factor * 0.7) + 23 * factor)
        b = int(cb * (1 - factor * 0.7) + 42 * factor)
        draw.line([(0, y), (w, y)], fill=(r, g, b))

    # Inner decorative border
    draw.rounded_rectangle([(20, 20), (w - 20, h - 20)], radius=16, outline=(255, 255, 255, 60), width=2)
    # Center badge
    draw.rounded_rectangle([(80, 100), (w - 80, h - 100)], radius=20, fill=(15, 23, 42), outline=color_rgb, width=3)

    font_title = _get_font(28, bold=True)
    font_sub = _get_font(16, bold=False)

    draw.text((w // 2, 170), name.upper(), fill=(255, 255, 255), font=font_title, anchor="mm")
    draw.text((w // 2, 225), "EXPLORE CERTIFIED INVENTORY", fill=(148, 163, 184), font=font_sub, anchor="mm")

    buf = io.BytesIO()
    img.save(buf, format="JPEG", quality=90)
    return buf.getvalue()


def generate_vehicle_image(
    title: str,
    brand_name: str,
    category_name: str,
    year: int,
    fuel: str,
    transmission: str,
    km_driven: int,
    price: Decimal,
    offer_price: Decimal | None,
    location: str,
    view_type: str = "EXTERIOR 3/4 VIEW",
    view_num: int = 1,
) -> bytes:
    """Generate a professional 800x520 studio vehicle showcase photo."""
    w, h = 800, 520
    img = Image.new("RGB", (w, h), (15, 23, 42))
    draw = ImageDraw.Draw(img)

    # 1. Background studio lighting gradient
    cat_lower = category_name.lower()
    if "electric" in cat_lower:
        base_accent = (6, 95, 110)
    elif "luxury" in cat_lower:
        base_accent = (80, 45, 15)
    elif "motorcycle" in cat_lower or "scooter" in cat_lower:
        base_accent = (90, 40, 10)
    elif "suv" in cat_lower:
        base_accent = (6, 78, 59)
    else:
        base_accent = (30, 58, 110)

    for y in range(h):
        factor = y / h
        r = int(12 + base_accent[0] * 0.4 * (1 - factor) + 15 * factor)
        g = int(18 + base_accent[1] * 0.4 * (1 - factor) + 23 * factor)
        b = int(28 + base_accent[2] * 0.4 * (1 - factor) + 38 * factor)
        draw.line([(0, y), (w, y)], fill=(r, g, b))

    # 2. Studio soft light oval in center
    for r in range(160, 0, -25):
        alpha = int((1 - r / 160) * 35)
        draw.ellipse([(w // 2 - r * 2, 230 - r), (w // 2 + r * 2, 230 + r)], fill=(25 + alpha, 38 + alpha, 60 + alpha))

    # 3. Horizon & reflection floor
    draw.line([(30, 360), (w - 30, 360)], fill=(71, 85, 105), width=2)
    draw.polygon([(30, 362), (w - 30, 362), (w - 70, 425), (70, 425)], fill=(18, 26, 42))

    # 4. Draw stylized vehicle body silhouette or cockpit depending on view_num
    if view_num == 1:
        # Exterior view silhouette
        if "motorcycle" in cat_lower or "bike" in cat_lower:
            # Motorcycle silhouette
            draw.polygon([(320, 270), (370, 240), (430, 245), (470, 275), (440, 310), (330, 310)], fill=(225, 29, 72))
            draw.line([(360, 235), (390, 215), (420, 215)], fill=(241, 245, 249), width=4)
            draw.ellipse([(280, 280), (350, 350)], fill=(15, 23, 42), outline=(148, 163, 184), width=5)
            draw.ellipse([(450, 280), (520, 350)], fill=(15, 23, 42), outline=(148, 163, 184), width=5)
        elif "scooter" in cat_lower:
            # Scooter silhouette
            draw.polygon([(330, 280), (370, 280), (420, 250), (470, 255), (480, 310), (330, 310)], fill=(147, 51, 234))
            draw.line([(350, 280), (370, 230), (390, 215)], fill=(241, 245, 249), width=4)
            draw.ellipse([(310, 295), (365, 350)], fill=(15, 23, 42), outline=(148, 163, 184), width=4)
            draw.ellipse([(450, 295), (505, 350)], fill=(15, 23, 42), outline=(148, 163, 184), width=4)
        elif "suv" in cat_lower:
            # SUV silhouette
            suv_body = [
                (170, 290), (180, 235), (250, 225), (320, 160), (520, 160),
                (600, 215), (640, 235), (640, 290), (600, 290),
                (580, 260), (520, 260), (500, 290),
                (320, 290), (300, 260), (240, 260), (220, 290)
            ]
            draw.polygon(suv_body, fill=(37, 99, 235))
            # Roof rails
            draw.line([(320, 153), (510, 153)], fill=(203, 213, 225), width=3)
            # Windows
            draw.polygon([(330, 170), (410, 170), (410, 220), (275, 220)], fill=(15, 23, 42))
            draw.polygon([(425, 170), (510, 170), (580, 220), (425, 220)], fill=(15, 23, 42))
            # Wheels
            draw.ellipse([(230, 260), (295, 325)], fill=(15, 23, 42), outline=(203, 213, 225), width=5)
            draw.ellipse([(515, 260), (580, 325)], fill=(15, 23, 42), outline=(203, 213, 225), width=5)
        elif "sedan" in cat_lower:
            # Sedan sleek aerodynamic silhouette
            sedan_body = [
                (160, 295), (175, 260), (230, 245), (320, 180), (490, 180),
                (570, 245), (650, 260), (650, 295), (600, 295),
                (580, 265), (520, 265), (500, 295),
                (320, 295), (300, 265), (240, 265), (220, 295)
            ]
            draw.polygon(sedan_body, fill=(14, 116, 144))
            draw.polygon([(330, 190), (410, 190), (410, 238), (265, 238)], fill=(15, 23, 42))
            draw.polygon([(425, 190), (480, 190), (555, 238), (425, 238)], fill=(15, 23, 42))
            draw.ellipse([(230, 265), (295, 330)], fill=(15, 23, 42), outline=(203, 213, 225), width=5)
            draw.ellipse([(515, 265), (580, 330)], fill=(15, 23, 42), outline=(203, 213, 225), width=5)
        else:
            # Compact / Hatchback / Luxury
            hatch_body = [
                (180, 295), (190, 255), (240, 245), (310, 185), (510, 185),
                (550, 245), (630, 260), (630, 295), (590, 295),
                (570, 265), (510, 265), (490, 295),
                (330, 295), (310, 265), (250, 265), (230, 295)
            ]
            draw.polygon(hatch_body, fill=(99, 102, 241))
            draw.polygon([(320, 195), (410, 195), (410, 238), (270, 238)], fill=(15, 23, 42))
            draw.polygon([(425, 195), (500, 195), (535, 238), (425, 238)], fill=(15, 23, 42))
            draw.ellipse([(240, 265), (305, 330)], fill=(15, 23, 42), outline=(203, 213, 225), width=5)
            draw.ellipse([(500, 265), (565, 330)], fill=(15, 23, 42), outline=(203, 213, 225), width=5)
    else:
        # Cockpit & Technology View
        draw.rounded_rectangle([(180, 140), (620, 330)], radius=16, fill=(30, 41, 59), outline=(71, 85, 105), width=2)
        # Touchscreen monitor representation
        draw.rounded_rectangle([(330, 160), (470, 250)], radius=8, fill=(15, 23, 42), outline=(56, 189, 248), width=2)
        # Steering representation
        draw.ellipse([(210, 190), (300, 280)], fill=(15, 23, 42), outline=(148, 163, 184), width=6)
        # Instrument cluster
        draw.rounded_rectangle([(230, 160), (280, 185)], radius=4, fill=(2, 132, 199))
        # Center console controls
        draw.line([(350, 275), (450, 275)], fill=(71, 85, 105), width=3)
        draw.line([(350, 295), (450, 295)], fill=(71, 85, 105), width=3)
        # Passenger seat / air vent representation
        draw.rounded_rectangle([(500, 170), (590, 290)], radius=12, fill=(20, 29, 47), outline=(51, 65, 85))

    # Fonts
    font_bold_lg = _get_font(24, bold=True)
    font_bold_md = _get_font(18, bold=True)
    font_sm = _get_font(14, bold=False)
    font_badge = _get_font(12, bold=True)

    # 5. Top badges
    # Brand pill
    draw.rounded_rectangle([(30, 25), (30 + 150, 58)], radius=8, fill=(37, 99, 235))
    draw.text((105, 41), brand_name.upper(), fill=(255, 255, 255), font=font_badge, anchor="mm")

    # Angle label top-right
    draw.rounded_rectangle([(w - 240, 25), (w - 30, 58)], radius=8, fill=(30, 41, 59), outline=(71, 85, 105))
    draw.text((w - 135, 41), f"ANGLE {view_num}/2 · {view_type}", fill=(203, 213, 225), font=font_badge, anchor="mm")

    # 6. Quality Stamp top-center
    draw.rounded_rectangle([(w // 2 - 130, 25), (w // 2 + 130, 58)], radius=8, fill=(16, 185, 129))
    draw.text((w // 2, 41), "★ CERTIFIED 150-PT INSPECTION ★", fill=(255, 255, 255), font=font_badge, anchor="mm")

    # 7. Bottom Card Bar
    draw.rounded_rectangle([(30, 435), (w - 30, 500)], radius=12, fill=(15, 23, 42), outline=(51, 65, 85), width=2)
    # Title & Specs
    draw.text((48, 452), title[:36], fill=(255, 255, 255), font=font_bold_md)
    sub = f"{year} · {transmission} · {fuel.capitalize()} · {km_driven:,} km · {location}"
    draw.text((48, 478), sub, fill=(148, 163, 184), font=font_sm)

    # Price Badge on Right
    display_price = offer_price if offer_price else price
    draw.text((w - 48, 452), f"₹{display_price:,.0f}", fill=(34, 197, 94), font=font_bold_lg, anchor="ra")
    if offer_price and offer_price < price:
        draw.text((w - 48, 480), f"MRP ₹{price:,.0f}", fill=(148, 163, 184), font=font_sm, anchor="ra")

    buf = io.BytesIO()
    img.save(buf, format="JPEG", quality=88)
    return buf.getvalue()


